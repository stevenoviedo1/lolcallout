#!/usr/bin/env node
/**
 * Regenerates models/lolcoach/Modelfile from COACH_SYSTEM_PROMPT_SMALL so the
 * Ollama model and the agent always share the same short system prompt.
 * Usage: npm run build -w @riftcoach/prompts && node scripts/gen-modelfile.mjs [--base <model-or-gguf>]
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { COACH_SYSTEM_PROMPT_SMALL } = await import(
  path.join(root, "packages/prompts/dist/index.js")
);
const i = process.argv.indexOf("--base");
const base = i > -1 ? process.argv[i + 1] : "qwen2.5:3b-instruct";
if (COACH_SYSTEM_PROMPT_SMALL.includes('"""')) throw new Error('prompt contains """');

const out = `# LOLCallout local coach model (generated by scripts/gen-modelfile.mjs — edit the prompt in packages/prompts)
# Create:  ollama create lolcoach -f models/lolcoach/Modelfile
# After fine-tuning, point FROM at your GGUF, e.g.  FROM ./lolcoach-q4_k_m.gguf  (see docs/LOCAL_AI.md)
FROM ${base}

# Short, steady callouts. The agent still sends per-intent temperature/max_tokens per request.
PARAMETER temperature 0.3
PARAMETER top_p 0.9
PARAMETER repeat_penalty 1.1
PARAMETER num_ctx 4096
PARAMETER num_predict 320
PARAMETER stop "<|im_end|>"

SYSTEM """${COACH_SYSTEM_PROMPT_SMALL}"""
`;
const dest = path.join(root, "models/lolcoach/Modelfile");
fs.writeFileSync(dest, out);
console.log(`wrote ${path.relative(root, dest)} (FROM ${base})`);
